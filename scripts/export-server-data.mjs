#!/usr/bin/env node
// Generates football/football_server/lib/src/data/world_cup_data.dart from the
// TypeScript team + schedule files, so the server simulates groups from the
// same squads and fixtures the client plays. Run after editing a roster/rating:
//   npm run export:data
import { build } from 'esbuild';
import { mkdirSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
const tmp = mkdtempSync(join(tmpdir(), 'wc-export-'));
const out = join(tmp, 'bundle.mjs');

await build({
  entryPoints: [join(root, 'src/client/game/teams/schedule.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: out,
  logLevel: 'error',
});

const { GROUPS, MATCHES } = await import(pathToFileURL(out).href);

// Same rule as nationId() in teams/index.ts.
const nationId = (t) =>
  t.name.toLowerCase().normalize('NFD').replace(/[^a-z]/g, '');

const strength = (t) =>
  Math.round((t.players.reduce((s, p) => s + p.ratings.ovr, 0) / t.players.length) * 10) / 10;

const nations = new Map();
for (const g of Object.values(GROUPS)) {
  for (const t of g) nations.set(nationId(t), t);
}
if (nations.size !== 48) throw new Error(`expected 48 nations, got ${nations.size}`);
if (MATCHES.length !== 72) throw new Error(`expected 72 fixtures, got ${MATCHES.length}`);

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lines = [];
lines.push('// GENERATED by scripts/export-server-data.mjs — do not edit by hand.');
lines.push('');
lines.push('class WcNation {');
lines.push('  final String id;');
lines.push('  final String name;');
lines.push('  final String group;');
lines.push('  /// Average overall of the starting eleven.');
lines.push('  final double strength;');
lines.push('  const WcNation(this.id, this.name, this.group, this.strength);');
lines.push('}');
lines.push('');
lines.push('class WcFixture {');
lines.push('  final String group;');
lines.push('  final DateTime kickoffUtc;');
lines.push('  final String home;');
lines.push('  final String away;');
lines.push('  final String venue;');
lines.push('  const WcFixture(this.group, this.kickoffUtc, this.home, this.away, this.venue);');
lines.push('}');
lines.push('');
lines.push('const wcNations = <String, WcNation>{');
for (const [group, teams] of Object.entries(GROUPS)) {
  for (const t of teams) {
    lines.push(`  ${q(nationId(t))}: WcNation(${q(nationId(t))}, ${q(t.name)}, ${q(group)}, ${strength(t)}),`);
  }
}
lines.push('};');
lines.push('');
lines.push('final wcFixtures = <WcFixture>[');
for (const m of MATCHES) {
  const d = m.kickoffUTC;
  lines.push(
    `  WcFixture(${q(m.group)}, DateTime.utc(${d.getUTCFullYear()}, ${d.getUTCMonth() + 1}, ${d.getUTCDate()}, ${d.getUTCHours()}, ${d.getUTCMinutes()}), ${q(nationId(m.home))}, ${q(nationId(m.away))}, ${q(m.venue)}),`,
  );
}
lines.push('];');
lines.push('');

const dest = join(root, 'football/football_server/lib/src/data/world_cup_data.dart');
mkdirSync(join(dest, '..'), { recursive: true });
writeFileSync(dest, lines.join('\n'));
console.log(`wrote ${dest} (${nations.size} nations, ${MATCHES.length} fixtures)`);
